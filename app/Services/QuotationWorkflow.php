<?php

namespace App\Services;

use App\Models\Contract;
use App\Models\Quotation;
use App\Models\User;
use App\Support\Audit;
use Illuminate\Support\Facades\DB;

/** Issuing a quotation, recording the client's answer, and turning an accepted quotation into its contract. */
class QuotationWorkflow
{
    public function __construct(private ContractLifecycle $lifecycle) {}

    /** First send emails the client; re-saving an already sent quotation does not email again. Returns true when it emailed. */
    public function send(Quotation $quotation): bool
    {
        $first = $quotation->sent_at === null;
        $quotation->forceFill(['status' => 'sent', 'sent_at' => $quotation->sent_at ?? now()])->save();
        if ($first) {
            app(Notifier::class)->quotationSent($quotation->fresh(['client.users']));
        }

        return $first;
    }

    /**
     * Accept or decline. The client answers in the portal; an admin can record an answer given by phone or email,
     * in which case only the client is emailed. Accepting generates the contract and, when the quotation says so,
     * sends it straight out for signature. Re-recording the same answer changes nothing and sends nothing.
     *
     * Returns the contract generated by this acceptance, or null.
     */
    public function answer(Quotation $quotation, bool $accepted, ?User $by = null): ?Contract
    {
        $status = $accepted ? 'accepted' : 'declined';
        // Locked so a double-click or two people answering at once cannot create two contracts.
        [$changed, $contract] = DB::transaction(function () use ($quotation, $accepted, $status) {
            $locked = Quotation::lockForUpdate()->findOrFail($quotation->id);
            if ($locked->status === $status) {
                return [false, null];
            }
            $locked->forceFill($accepted ? ['status' => 'accepted', 'accepted_at' => now(), 'declined_at' => null] : ['status' => 'declined', 'declined_at' => now(), 'accepted_at' => null])->save();

            return [true, $accepted && ! $locked->contract_id ? $this->createContract($locked) : null];
        });
        $quotation->refresh();
        if (! $changed) {
            return null;
        }

        $sent = false;
        if ($contract && $quotation->auto_send_contract && ContractLifecycle::canSendForSignature($contract)) {
            $this->lifecycle->sendForSignature($contract, $by, clientNote: 'Thank you for accepting quotation '.$quotation->reference.'. Your contract has been prepared from it.', notifyAdmins: false);
            $sent = true;
        }
        app(Notifier::class)->quotationAnswered($quotation->load('client.users'), $accepted, notifyAdmins: ! $by?->isAdmin(), contract: $contract, contractSent: $sent);

        return $contract?->fresh();
    }

    /**
     * A draft contract built from the quotation: same client, title, amount and currency, the line items as its scope,
     * and the type, billing and term chosen on the quotation. One contract per quotation.
     */
    public function createContract(Quotation $quotation): Contract
    {
        return DB::transaction(function () use ($quotation) {
            $quotation->loadMissing('items', 'client');
            $start = now()->startOfDay();
            $contract = Contract::create([
                'client_id' => $quotation->client_id,
                'title' => $quotation->title,
                'type' => $quotation->contract_type ?? array_key_first(config('company.contract_types')),
                'billing_cycle' => $quotation->billing_cycle ?? 'one_time',
                'start_date' => $start,
                'end_date' => $quotation->contract_term_months ? $start->copy()->addMonths($quotation->contract_term_months)->subDay() : null,
                'amount' => $quotation->total,
                'currency' => $quotation->currency,
                'payment_terms_days' => 14,
                'client_signatory' => $quotation->client->contact_name,
                'company_signatory' => config('company.signatory'),
                'status' => 'draft',
                'scope' => $quotation->items->map(fn ($i) => '- '.str_replace("\n", "\n  ", trim($i->description)))->implode("\n"),
            ]);
            $quotation->forceFill(['contract_id' => $contract->id])->save();
            Audit::log($contract, 'created', ['status' => 'draft', 'from_quotation' => $quotation->reference]);

            return $contract;
        });
    }
}
